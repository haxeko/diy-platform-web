import { z } from "zod";

/** Chip families esptool-js can report via `ESPLoader.main()` that this site supports. */
export const CHIP_FAMILIES = [
  "ESP32",
  "ESP32-S2",
  "ESP32-S3",
  "ESP32-C2",
  "ESP32-C3",
  "ESP32-C5",
  "ESP32-C6",
  "ESP32-C61",
  "ESP32-H2",
  "ESP32-H21",
  "ESP32-H4",
  "ESP32-P4",
  "ESP8266",
] as const;

export const ChipFamilySchema = z.enum(CHIP_FAMILIES);
export type ChipFamily = z.infer<typeof ChipFamilySchema>;

export const PROTOCOLS = [
  "Matter over Thread",
  "Matter over Wi-Fi",
  "Thread",
  "Zigbee",
  "Wi-Fi",
  "BLE",
  "ESP-NOW",
] as const;
export const ProtocolSchema = z.enum(PROTOCOLS);
export type Protocol = z.infer<typeof ProtocolSchema>;

export const DIFFICULTIES = ["easy", "medium", "hard"] as const;
export const DifficultySchema = z.enum(DIFFICULTIES);
export type Difficulty = z.infer<typeof DifficultySchema>;

/** Soft iOS-like tints used for project/firmware cards. */
export const ACCENTS = ["sky", "mint", "lavender", "peach", "lemon", "rose", "graphite"] as const;
export const AccentSchema = z.enum(ACCENTS);
export type Accent = z.infer<typeof AccentSchema>;

const slug = z
  .string()
  .min(1)
  .max(80)
  .regex(/^[a-z0-9]+(?:-[a-z0-9]+)*$/, "slug phải là chữ thường, số và dấu gạch ngang");

const fileName = z
  .string()
  .min(1)
  .max(120)
  .regex(/^[A-Za-z0-9][A-Za-z0-9._-]*$/, "tên file chỉ gồm chữ, số, dấu chấm, gạch ngang/dưới")
  .refine((v) => !v.includes(".."), "tên file không được chứa '..'");

/** Flash offsets may be written as a number or a hex string ("0x10000"). */
const flashOffset = z
  .union([z.number().int().nonnegative(), z.string().regex(/^0x[0-9a-fA-F]+$/)])
  .transform((v) => (typeof v === "string" ? Number.parseInt(v, 16) : v));

export const FirmwarePartSchema = z.object({
  /** Flash address the binary is written to. */
  offset: flashOffset,
  /** File name inside firmware/<firmwareId>/<version>/ (never a path). */
  file: fileName,
  /** Optional human label such as "bootloader", "partition-table", "app". */
  label: z.string().max(60).optional(),
  /** Optional SHA-256 (hex) of the plaintext file; verified by the server before issuing a session. */
  sha256: z.string().regex(/^[0-9a-f]{64}$/, "sha256 phải là 64 ký tự hex thường").optional(),
});
export type FirmwarePart = z.infer<typeof FirmwarePartSchema>;

export const FLASH_MODES = ["keep", "dio", "qio", "dout", "qout"] as const;
/** Only values every ROM target can encode; "keep" (recommended) leaves the image header untouched. */
export const FLASH_FREQS = ["keep", "80m", "40m", "26m", "20m"] as const;
export const FLASH_SIZES = [
  "keep",
  "detect",
  "256KB",
  "512KB",
  "1MB",
  "2MB",
  "4MB",
  "8MB",
  "16MB",
  "32MB",
  "64MB",
  "128MB",
] as const;

export const FirmwareBuildSchema = z.object({
  chipFamily: ChipFamilySchema,
  parts: z.array(FirmwarePartSchema).min(1),
  flashMode: z.enum(FLASH_MODES).default("keep"),
  flashFreq: z.enum(FLASH_FREQS).default("keep"),
  flashSize: z.enum(FLASH_SIZES).default("keep"),
  /** Force a full chip erase before writing (wipes Wi-Fi/Matter fabric data). The UI also offers it as "Cài mới". */
  eraseAll: z.boolean().default(false),
});
export type FirmwareBuild = z.infer<typeof FirmwareBuildSchema>;

export const FirmwareManifestSchema = z.object({
  id: slug,
  name: z.string().min(1).max(120),
  version: z
    .string()
    .min(1)
    .max(40)
    .regex(/^[A-Za-z0-9][A-Za-z0-9._-]*$/, "version chỉ gồm chữ, số, dấu chấm, gạch ngang/dưới"),
  /** Slug of the project this firmware belongs to. */
  project: slug,
  summary: z.string().min(1).max(300),
  releasedAt: z.string().regex(/^\d{4}-\d{2}-\d{2}$/, "releasedAt dạng YYYY-MM-DD"),
  status: z.enum(["stable", "beta", "deprecated"]).default("stable"),
  changelog: z.array(z.string()).default([]),
  builds: z
    .array(FirmwareBuildSchema)
    .min(1)
    .refine((b) => new Set(b.map((x) => x.chipFamily)).size === b.length, "mỗi chipFamily chỉ được xuất hiện một lần trong builds"),
  /** Step-by-step instructions shown under the flasher after a successful flash. */
  afterFlash: z.array(z.string()).default([]),
  tags: z.array(z.string()).default([]),
  /** Marks placeholder binaries generated by `npm run firmware:demo`; the UI shows a badge. */
  demo: z.boolean().default(false),
  /** Licence of the firmware, e.g. "Apache-2.0", "GPL-3.0", "Source-available (dùng cá nhân)". */
  license: z.string().max(80).optional(),
  /** Link to the source code / build recipe (required in spirit for GPL-derived builds). */
  source: z.string().url().max(300).optional(),
  /** Minimum flash size the image needs, in MB (checked against the detected flash size). */
  minFlashMB: z.number().int().positive().optional(),
  /** Fallback Matter pairing info when the device does not print it on boot. */
  pairing: z
    .object({
      qr: z.string().max(120).optional(),
      manualCode: z.string().max(24).optional(),
    })
    .optional(),
});
export type FirmwareManifest = z.infer<typeof FirmwareManifestSchema>;

export const BomItemSchema = z.object({
  name: z.string().min(1),
  qty: z.union([z.number(), z.string()]).default(1),
  note: z.string().optional(),
});
export type BomItem = z.infer<typeof BomItemSchema>;

export const ProjectFrontmatterSchema = z.object({
  title: z.string().min(1).max(120),
  summary: z.string().min(1).max(300),
  protocol: ProtocolSchema,
  chips: z.array(ChipFamilySchema).min(1),
  difficulty: DifficultySchema,
  /** Rough build time in minutes. */
  timeMinutes: z.number().int().positive(),
  features: z.array(z.string()).default([]),
  bom: z.array(BomItemSchema).default([]),
  /** Firmware manifest ids published for this project. */
  firmware: z.array(slug).default([]),
  /** Related guide slugs. */
  guides: z.array(slug).default([]),
  tags: z.array(z.string()).default([]),
  accent: AccentSchema.default("sky"),
  /** Emoji or short glyph used as the card icon. */
  icon: z.string().min(1).max(8).default("◎"),
  featured: z.boolean().default(false),
  /** Project touches mains voltage (220 V) — shows a safety badge and callout. */
  mains: z.boolean().default(false),
  updatedAt: z.string().regex(/^\d{4}-\d{2}-\d{2}$/),
});
export type ProjectFrontmatter = z.infer<typeof ProjectFrontmatterSchema>;

export interface Project extends ProjectFrontmatter {
  slug: string;
  /** Markdown body (GFM). */
  body: string;
}

export const GUIDE_CATEGORIES = ["bat-dau", "flash", "matter", "thread", "home-assistant", "phan-cung", "khac-phuc"] as const;
export const GuideCategorySchema = z.enum(GUIDE_CATEGORIES);
export type GuideCategory = z.infer<typeof GuideCategorySchema>;

export const GuideFrontmatterSchema = z.object({
  title: z.string().min(1).max(120),
  summary: z.string().min(1).max(300),
  category: GuideCategorySchema,
  order: z.number().int().default(100),
  projects: z.array(slug).default([]),
  updatedAt: z.string().regex(/^\d{4}-\d{2}-\d{2}$/),
});
export type GuideFrontmatter = z.infer<typeof GuideFrontmatterSchema>;

export interface Guide extends GuideFrontmatter {
  slug: string;
  body: string;
}
